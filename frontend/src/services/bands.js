// Helper: 获取乐队样式对象
export const getBandStyle = (bandId) => {
    const band = bands.find(b => b.id === bandId);
    if (!band || !band.color) return { background: '#eee' };
    return { background: band.color };
};

// Helper: 获取乐队图标 URL
// 资源已移动到 public/bands/ 目录，直接以绝对路径访问，无需构建时解析
export const getBandIconUrl = (bandId) => {
    const band = bands.find(b => b.id === bandId);
    // 默认 fallback 到 bandId，如果配置中有 iconId 则使用 iconId
    const resId = band ? (band.iconId || band.id) : bandId;

    // 直接返回 public 目录下的路径 (Vite 会自动处理根路径)
    // 这种方式完全绕过了 import 分析，避免了构建器解析错误
    return `/bands/band_${resId}.svg`;
};
